// Structure and configuration tests: they inspect the code and the startup
// without starting the API.
import { test } from "node:test";
import assert from "node:assert/strict";
import { access } from "node:fs/promises";
import path from "node:path";
import { ROOT, read, runServer, finish } from "./helpers.js";

const exists = (route) => access(path.join(ROOT, route)).then(() => true, () => false);

test.after(() => finish());

test("H01 · the backend is split into MVC layers (routes, controllers, services, models)", async () => {
  for (const folder of ["routes", "controllers", "services", "models", "validators", "middlewares", "frontend"]) {
    assert.ok(await exists(folder), `folder ${folder}/ is missing`);
  }
  // Only the models (and the database layer) contain SQL.
  for (const file of ["controllers/enrollmentController.js", "services/courseService.js", "routes/courseRoutes.js"]) {
    const code = await read(file);
    assert.doesNotMatch(code, /\b(SELECT|INSERT|UPDATE)\b/, `${file} should not contain SQL`);
  }
});

test("H12 · configuration comes from the environment and an invalid value stops startup", async () => {
  const { code, output } = await runServer({ PORT: "abc" });
  assert.notEqual(code, 0);
  assert.match(output, /Invalid PORT/);
});

test("H12 · without DATABASE_URL the server does not start and explains why", async () => {
  const { code, output } = await runServer({ DATABASE_URL: "" });
  assert.notEqual(code, 0);
  assert.match(output, /DATABASE_URL/);
});

test("H07 · in production it does not start without the identity provider (ADR-05)", async () => {
  const { code, output } = await runServer({ NODE_ENV: "production" });
  assert.notEqual(code, 0);
  assert.match(output, /OIDC_ISSUER/);
});

test("H09 · IDs are generated by PostgreSQL (IDENTITY) and Math.max is no longer used", async () => {
  const schema = await read("database/schema.sql");
  assert.equal((schema.match(/GENERATED ALWAYS AS IDENTITY/g) ?? []).length, 3);
  for (const [folder, suffix] of [["services", "Service"], ["models", "Model"], ["controllers", "Controller"]]) {
    for (const name of ["course", "student", "enrollment"]) {
      assert.doesNotMatch(await read(`${folder}/${name}${suffix}.js`), /Math\.max/);
    }
  }
});

test("H13 · the frontend is split into api.js, ui.js and main.js; only api.js uses fetch", async () => {
  const [api, ui, main] = await Promise.all(["api", "ui", "main"].map((n) => read(`frontend/js/${n}.js`)));
  assert.equal((api.match(/fetch\(/g) ?? []).length, 1, "there must be a single fetch, inside the common function");
  assert.match(api, /response\.ok/, "api.js must check response.ok");
  assert.doesNotMatch(ui, /fetch\(/);
  assert.doesNotMatch(main, /fetch\(/);
  assert.match(await read("frontend/index.html"), /type="module"/);
});

test("H05 · the frontend never inserts HTML with innerHTML, outerHTML or insertAdjacentHTML", async () => {
  for (const name of ["api", "ui", "main"]) {
    const code = await read(`frontend/js/${name}.js`);
    assert.doesNotMatch(code, /\.(innerHTML|outerHTML)\s*[+]?=|insertAdjacentHTML|document\.write/, `${name}.js`);
  }
});

test("H15 · package.json pins Node 24, exact versions and the project scripts", async () => {
  const pkg = JSON.parse(await read("package.json"));
  assert.equal(pkg.type, "module");
  assert.equal(pkg.engines.node, ">=24");
  for (const [name, version] of Object.entries(pkg.dependencies)) {
    assert.match(version, /^\d+\.\d+\.\d+$/, `${name} must have an exact version`);
  }
  for (const script of ["start", "dev", "test", "db:reset"]) assert.ok(pkg.scripts[script], `script ${script} is missing`);
  assert.equal((await read(".nvmrc")).trim(), "24");
  assert.ok(await exists(pkg.main), `main points to ${pkg.main}, which must exist`);
  assert.ok(await exists("tests"), "the tests folder exists");
});
